static void ShutdownCUDA( void )
{
	if ( s_cuModule )  { cu.ModuleUnload( s_cuModule );  s_cuModule = NULL; }
	if ( s_cuContext ) { cu.CtxDestroy( s_cuContext );   s_cuContext = NULL; }
	s_cuKernel = NULL;
	if ( cu.hLib )
	{
		FreeLibrary( cu.hLib );
		memset( &cu, 0, sizeof( cu ) );
	}
}

// Tries to initialise CUDA: NVIDIA GPU with compute capability >= 7.5, context,
// PTX module. On failure (no driver, GPU too old, PTX rejected by an outdated
// driver...) returns false with nothing left allocated: OpenCL takes over.
static bool InitCUDA( void )
{
	if ( !LoadCUDA() )
	{
		ShutdownCUDA();
		return false;
	}
	int count = 0;
	if ( cu.Init( 0 ) != 0 || cu.DeviceGetCount( &count ) != 0 || count <= 0 )
	{
		ShutdownCUDA();
		return false;
	}

	int chosen = -1, bestSM = -1;
	const char *penv = getenv( "VVIS_GPU_DEVICE" );
	int forced = ( penv && *penv ) ? atoi( penv ) : -1;
	for ( int i = 0; i < count; ++i )
	{
		CUdevice dev;
		int major = 0, minor = 0, sm = 0;
		if ( cu.DeviceGet( &dev, i ) != 0 )
			continue;
		cu.DeviceGetAttribute( &major, CU_DEV_ATTR_CC_MAJOR, dev );
		cu.DeviceGetAttribute( &minor, CU_DEV_ATTR_CC_MINOR, dev );
		cu.DeviceGetAttribute( &sm, CU_DEV_ATTR_MULTIPROCESSOR_COUNT, dev );
		if ( major < 7 || ( major == 7 && minor < 5 ) )
			continue;
		if ( forced >= 0 )
		{
			if ( i == forced ) { chosen = i; break; }
			continue;
		}
		if ( sm > bestSM ) { bestSM = sm; chosen = i; }
	}
	if ( chosen < 0 )
	{
		ShutdownCUDA();
		return false;
	}

	CUdevice dev;
	char name[256] = { 0 };
	size_t mem = 0;
	cu.DeviceGet( &dev, chosen );
	cu.DeviceGetName( name, (int)sizeof( name ) - 1, dev );
	cu.DeviceTotalMem( &mem, dev );

	if ( cu.CtxCreate( &s_cuContext, 0, dev ) != 0 )
	{
		ShutdownCUDA();
		return false;
	}
	CUresult r = cu.ModuleLoadData( &s_cuModule, g_RaycastPTX );
	if ( r != 0 || cu.ModuleGetFunction( &s_cuKernel, s_cuModule, "RaycastStabKernel" ) != 0 )
	{
		fprintf( stderr, "[VVIS GPU] CUDA: PTX kernel load rejected (%d), driver too old? Falling back to OpenCL.\n", r );
		ShutdownCUDA();
		return false;
	}
	if ( g_bVisDebug )
		Msg( "[VVIS GPU] CUDA device %d/%d : %s (%llu MB)\n", chosen, count, name, (unsigned long long)( mem / ( 1024 * 1024 ) ) );
	return true;
}

// Progress (0..1) once pairs [0, pairEnd) have been processed. rowProgress[r] =
// fraction of the candidate pairs in rows (source portals) < r: the work is
// concentrated on the candidates, not spread evenly over all n*n pairs.
static float PairProgress( const float *rowProgress, int numPortals, unsigned long long pairEnd )
{
	if ( !rowProgress || numPortals <= 0 )
		return 0.0f;
	unsigned long long row = pairEnd / (unsigned long long)numPortals;
	if ( row > (unsigned long long)numPortals )
		row = numPortals;
	return rowProgress[row];
}

// Maps the current pass's progress onto the global bar (a single bar outside -debug).
static float s_progBase = 0.0f, s_progScale = 1.0f;
static void ReportProgress( float passFraction )
{
	UpdatePacifier( s_progBase + s_progScale * passFraction );
}

// Portal edge margin: negative = a ray must pass clearly inside every portal. A positive
// margin (0.01, like ON_VIS_EPSILON) let through rays grazing the walls and made hidden
// areas visible.
static const float g_EdgeEps = -0.003f;

// CUDA equivalent of the OpenCL "buffers + kernel + readback" step. Same kernel,
// same chunking (anti-TDR), same results.
static bool RunRaycastCUDA( const GPUPortal *hPortals, size_t portalsBytes, int numPortals,
	const GPULeaf *hLeafs, size_t leafsBytes,
	const int *hLeafPortals, size_t leafPortalsBytes,
	const float *hWinding, size_t windingBytes,
	const unsigned char *hFlood, unsigned char *hVis, size_t visBytesPadded,
	int portalbytes_, int samples_, int maxSteps_, int flags_, float edgeEps_, int ringMask_, const float *rowProgress )
{
	CUdeviceptr dPortals = 0, dLeafs = 0, dLeafPortals = 0, dWinding = 0, dFlood = 0, dVis = 0;
	bool ok = true;
	int nLeafs = portalclusters;

#define CU_TRY( expr, what ) \
	if ( ok ) { CUresult r_ = ( expr ); if ( r_ != 0 ) { fprintf( stderr, "[VVIS GPU] CUDA %s failed (%d).\n", what, r_ ); ok = false; } }
#define CU_UPLOAD( var, host, bytes, what ) \
	CU_TRY( cu.MemAlloc( &var, bytes ), what ); \
	CU_TRY( cu.MemcpyHtoD( var, host, bytes ), what );

	CU_UPLOAD( dPortals, hPortals, portalsBytes, "portals" );
	CU_UPLOAD( dLeafs, hLeafs, leafsBytes, "leafs" );
	CU_UPLOAD( dLeafPortals, hLeafPortals, leafPortalsBytes, "leaf_portals" );
	CU_UPLOAD( dWinding, hWinding, windingBytes, "winding_pts" );
	CU_UPLOAD( dFlood, hFlood, visBytesPadded, "portalflood" );
	CU_TRY( cu.MemAlloc( &dVis, visBytesPadded ), "portalvis" );
	CU_TRY( cu.MemsetD8( dVis, 0, visBytesPadded ), "memset" );

	// Diagnostic statistics: only enabled when VVIS_GPU_STATS=1.
	const int statCount = 4 + 16 + 1;
	const char *stenv = getenv( "VVIS_GPU_STATS" );
	const bool wantStats = stenv && *stenv == '1';
	CUdeviceptr dStats = 0;
	if ( wantStats )
	{
		CU_TRY( cu.MemAlloc( &dStats, sizeof( unsigned long long ) * statCount ), "stats" );
		CU_TRY( cu.MemsetD8( dStats, 0, sizeof( unsigned long long ) * statCount ), "stats memset" );
	}

	const unsigned long long npairs = (unsigned long long)numPortals * (unsigned long long)numPortals;
	const unsigned int block = 128;
	const unsigned long long chunk = (unsigned long long)block * 16384;
	for ( unsigned long long start = 0; ok && start < npairs; start += chunk )
	{
		unsigned long long remaining = npairs - start;
		unsigned long long n = remaining < chunk ? remaining : chunk;
		unsigned int grid = (unsigned int)( ( n + block - 1 ) / block );
		unsigned long long startArg = start;
		void *args[] = { &dPortals, &numPortals, &dLeafs, &nLeafs, &dLeafPortals, &dWinding,
			&dFlood, &dVis, &portalbytes_, &samples_, &maxSteps_, &flags_, &edgeEps_, &ringMask_, &startArg, &dStats };
		CU_TRY( cu.LaunchKernel( s_cuKernel, grid, 1, 1, block, 1, 1, 0, NULL, args, NULL ), "cuLaunchKernel" );
		CU_TRY( cu.CtxSynchronize(), "cuCtxSynchronize" );
		if ( ok )
			ReportProgress( PairProgress( rowProgress, numPortals, start + n ) );
	}
	CU_TRY( cu.MemcpyDtoH( hVis, dVis, visBytesPadded ), "cuMemcpyDtoH" );

	if ( ok && wantStats )
	{
		unsigned long long st[4 + 16 + 1] = { 0 };
		CU_TRY( cu.MemcpyDtoH( st, dStats, sizeof( st ) ), "stats DtoH" );
		printf( "[VVIS GPU][STATS] pairs tested %llu, visible %llu, rays %llu (%llu of them for invisible pairs), walk steps %llu\n",
			st[0], st[1], st[2], st[3], st[20] );
		printf( "[VVIS GPU][STATS] depth at which missed rays die (portals crossed: rays):\n" );
		for ( int h = 0; h < 16; ++h )
			if ( st[4 + h] )
				printf( "[VVIS GPU][STATS]   %s%2d : %llu\n", h == 15 ? ">=" : "  ", h, st[4 + h] );
	}

#undef CU_UPLOAD
#undef CU_TRY

	if ( dPortals )     cu.MemFree( dPortals );
	if ( dLeafs )       cu.MemFree( dLeafs );
	if ( dLeafPortals ) cu.MemFree( dLeafPortals );
	if ( dWinding )     cu.MemFree( dWinding );
	if ( dFlood )       cu.MemFree( dFlood );
	if ( dVis )         cu.MemFree( dVis );
	if ( dStats )       cu.MemFree( dStats );
	return ok;
}

// --- GPU_Init ----------------------------------------------------------------

bool GPU_Init( void )
{
	// CUDA first (NVIDIA), then OpenCL (older NVIDIA, AMD, Intel).
	const char *be = getenv( "VVIS_GPU_BACKEND" );
	const bool forceOpenCL = be && !_stricmp( be, "opencl" );
	if ( !forceOpenCL && InitCUDA() )
	{
		s_backend = BACKEND_CUDA;
		return true;
	}

	if ( !LoadOpenCL() )
	{
		fprintf( stderr, "[VVIS GPU] OpenCL unavailable (OpenCL.dll missing or incomplete). Using CPU flow.\n" );
		GPU_Shutdown();
		return false;
	}

	cl_device_id devices[32];
	int numDevices = EnumerateGPUs( devices, 32 );
	if ( numDevices == 0 )
	{
		fprintf( stderr, "[VVIS GPU] No OpenCL GPU detected. Using CPU flow.\n" );
		GPU_Shutdown();
		return false;
	}

	int chosen = -1;
	const char *penv = getenv( "VVIS_GPU_DEVICE" );
	if ( penv && *penv )
	{
		int v = atoi( penv );
		if ( v >= 0 && v < numDevices )
			chosen = v;
	}
	if ( chosen < 0 )
	{
		cl_uint bestCU = 0;
		for ( int i = 0; i < numDevices; ++i )
		{
			cl_uint cu = 0;
			cl.GetDeviceInfo( devices[i], CL_DEVICE_MAX_COMPUTE_UNITS, sizeof( cu ), &cu, NULL );
			if ( chosen < 0 || cu > bestCU )
			{
				chosen = i;
				bestCU = cu;
			}
		}
	}
	s_device = devices[chosen];

	char name[256] = { 0 }, vendor[256] = { 0 };
	cl_ulong mem = 0;
	cl.GetDeviceInfo( s_device, CL_DEVICE_NAME, sizeof( name ) - 1, name, NULL );
	cl.GetDeviceInfo( s_device, CL_DEVICE_VENDOR, sizeof( vendor ) - 1, vendor, NULL );
	cl.GetDeviceInfo( s_device, CL_DEVICE_GLOBAL_MEM_SIZE, sizeof( mem ), &mem, NULL );
	if ( g_bVisDebug )
		Msg( "[VVIS GPU] OpenCL device %d/%d : %s (%s, %llu MB)\n",
			chosen, numDevices, name, vendor, (unsigned long long)( mem / ( 1024 * 1024 ) ) );

	cl_int err = CL_SUCCESS;
	s_context = cl.CreateContext( NULL, 1, &s_device, NULL, NULL, &err );
	if ( err != CL_SUCCESS )
	{
		fprintf( stderr, "[VVIS GPU] clCreateContext failed (%d). Using CPU flow.\n", err );
		GPU_Shutdown();
		return false;
	}
	s_queue = cl.CreateCommandQueue( s_context, s_device, 0, &err );
	if ( err != CL_SUCCESS )
	{
		fprintf( stderr, "[VVIS GPU] clCreateCommandQueue failed (%d). Using CPU flow.\n", err );
		GPU_Shutdown();
		return false;
	}

	// Correctly rounded division/sqrt here, and FP_CONTRACT OFF (no implicit FMA) in the
	// kernel source: results stay consistent from one vendor to another.
	const char *src = g_szRaycastKernelSource;
	s_program = cl.CreateProgramWithSource( s_context, 1, &src, NULL, &err );
	if ( err == CL_SUCCESS )
		err = cl.BuildProgram( s_program, 1, &s_device, "-cl-fp32-correctly-rounded-divide-sqrt", NULL, NULL );
	if ( err != CL_SUCCESS )
	{
		char log[8192] = { 0 };
		if ( s_program )
			cl.GetProgramBuildInfo( s_program, s_device, CL_PROGRAM_BUILD_LOG, sizeof( log ) - 1, log, NULL );
		fprintf( stderr, "[VVIS GPU] OpenCL kernel compilation failed (%d):\n%s\nUsing CPU flow.\n", err, log );
		GPU_Shutdown();
		return false;
	}
	s_kernel = cl.CreateKernel( s_program, "RaycastStabKernel", &err );
	if ( err != CL_SUCCESS )
	{
		fprintf( stderr, "[VVIS GPU] clCreateKernel failed (%d). Using CPU flow.\n", err );
		GPU_Shutdown();
		return false;
	}
	s_backend = BACKEND_OPENCL;
	return true;
}

// --- GPU_Shutdown --------------------------------------------------------------

void GPU_Shutdown( void )
{
	ShutdownCUDA();
	s_backend = BACKEND_NONE;
	if ( !cl.hLib )
		return;
	if ( s_kernel )  { cl.ReleaseKernel( s_kernel );        s_kernel = NULL; }
	if ( s_program ) { cl.ReleaseProgram( s_program );      s_program = NULL; }
	if ( s_queue )   { cl.ReleaseCommandQueue( s_queue );   s_queue = NULL; }
	if ( s_context ) { cl.ReleaseContext( s_context );      s_context = NULL; }
	s_device = NULL;
	if ( cl.hLib )
	{
		FreeLibrary( cl.hLib );
		memset( &cl, 0, sizeof( cl ) );
	}
}

// --- GPU_RunPortalFlowRaycast ---------------------------------------------------
// Fills portals[i].portalvis for every portal, in place of PortalFlow.
// Returns false, without modifying anything, if a GPU operation fails: VVIS then
// runs the original CPU flow.
//
// Steps:
//   1. Flatten the portals and their winding vertices (GPUPortal).
//   2. Flatten the leaf -> outgoing portals topology (GPULeaf).
//   3. Copy portalflood: it is the candidate pair filter.
//   4. For each pass: launch the kernel over chunks of pairs
//      (1 thread = 1 pair), then merge the result with a bitwise OR.
//   5. Copy the result into portal_t and mark it stat_done.
//
// Passes: passes[k] describes pass k (see GPUPassConfig in flow_gpu.h). Pass 0
// tests every candidate pair. Later passes only retest the candidates not yet
// proven visible:
//
//   candidates   = portalflood
//   pass 0       : test candidates              -> vis0
//   pass 1       : test candidates and not vis0 -> vis1
//   result       = vis0 OR vis1 ...
//
// A pass never removes visibility, it can only add more.
//
// Diagnostics: VVIS_GPU_STATS=1 (CUDA only) prints the number of rays cast
// and the depth at which missed rays die.

// Counts the set bits of a buffer (for the displayed percentages).
static size_t PopCountBytes( const unsigned char *p, size_t n )
{
	size_t c = 0, i = 0;
	for ( ; i + 8 <= n; i += 8 )
	{
		unsigned long long v;
		memcpy( &v, p + i, 8 );
		c += (size_t)__popcnt64( v );
	}
	for ( ; i < n; i++ )
		c += (size_t)__popcnt( p[i] );
	return c;
}

// Portals come in pairs (2k, 2k+1) = the two directions of the same portal. Since the
// line a -> b is also the line b -> a, a visible pair (i, j) implies that (j^1, i^1) is
// visible too, so it is copied over. Used with RAY_FLAG_MIRROR, where the kernel only
// tests one of the two directions.
static void SymmetrizeVis( unsigned char *vis, int numPortals, int portalbytes )
{
	for ( int i = 0; i < numPortals; i++ )
	{
		const unsigned long long *row = (const unsigned long long *)( vis + (size_t)i * portalbytes );
		const int nw = portalbytes / 8;
		for ( int w = 0; w < nw; w++ )
		{
			unsigned long long v = row[w];
			while ( v )
			{
				unsigned long idx;
				_BitScanForward64( &idx, v );
				v &= v - 1;
				const int j = w * 64 + (int)idx;
				if ( j >= numPortals )
					continue;
				vis[(size_t)( j ^ 1 ) * portalbytes + ( ( i ^ 1 ) >> 3 )] |= (unsigned char)( 1u << ( ( i ^ 1 ) & 7 ) );
			}
		}
	}
}

bool GPU_RunPortalFlowRaycast( int sorted_portal_count, const GPUPassConfig *passCfgIn, int numPasses )
{
	const int nportals = sorted_portal_count;
	const int numPortals = g_numportals * 2;
	if ( numPasses < 1 || numPasses > 16 || !passCfgIn )
		return false;
	GPUPassConfig passes[16];
	for ( int k = 0; k < numPasses; k++ )
		passes[k] = passCfgIn[k];

	// Outside -debug: a single bar for all passes. Weight of an auto dense pass = its
	// relative budget (it lasts ~budgetRel x the previous pass), 1 otherwise.
	float passWeight[16], totalWeight = 0.0f;
	for ( int k = 0; k < numPasses; k++ )
	{
		passWeight[k] = ( passes[k].flags & RAY_FLAG_AUTO ) ? max( 0.1f, passes[k].budgetRel ) : 1.0f;
		totalWeight += passWeight[k];
	}
	const ULONGLONG tFlow0 = GetTickCount64();
	if ( !g_bVisDebug )
	{
		VisUI_Label( "PortalFlow_RayGPU:" );
		StartPacifier( "" );
	}

	// -- 1. Portals + vertices ------------------------------------------------
	int totalWindingPts = 0;
	for ( int i = 0; i < numPortals; i++ )
		if ( portals[i].winding )
			totalWindingPts += portals[i].winding->numpoints;

	GPUPortal *hPortals = (GPUPortal *)calloc( numPortals > 0 ? numPortals : 1, sizeof( GPUPortal ) );
	float *hWindingPts = (float *)malloc( sizeof( float ) * 3 * ( totalWindingPts > 0 ? totalWindingPts : 1 ) );

	int wpt = 0;
	for ( int i = 0; i < numPortals; i++ )
	{
		portal_t *p = &portals[i];
		GPUPortal &gp = hPortals[i];
		gp.plane_normal[0]    = p->plane.normal[0];
		gp.plane_normal[1]    = p->plane.normal[1];
		gp.plane_normal[2]    = p->plane.normal[2];
		gp.plane_dist         = p->plane.dist;
		gp.leaf               = p->leaf;
		gp.origin[0]          = p->origin[0];
		gp.origin[1]          = p->origin[1];
		gp.origin[2]          = p->origin[2];
		gp.radius             = p->radius;
		gp.portalflood_offset = 0;
		gp.status             = (int)p->status;
		gp.nummightsee        = p->nummightsee;
		gp.winding_start      = wpt;
		gp.winding_count      = 0;
		if ( p->winding )
		{
			gp.winding_count = p->winding->numpoints;
			for ( int k = 0; k < p->winding->numpoints; k++ )
			{
				hWindingPts[( wpt + k ) * 3 + 0] = p->winding->points[k][0];
				hWindingPts[( wpt + k ) * 3 + 1] = p->winding->points[k][1];
				hWindingPts[( wpt + k ) * 3 + 2] = p->winding->points[k][2];
			}
			wpt += p->winding->numpoints;
		}
	}

	// -- 2. Leaf -> portal topology ---------------------------------------------
	int totalLeafPortals = 0;
	for ( int l = 0; l < portalclusters; l++ )
		totalLeafPortals += leafs[l].portals.Count();

	GPULeaf *hLeafs = (GPULeaf *)calloc( portalclusters > 0 ? portalclusters : 1, sizeof( GPULeaf ) );
	int *hLeafPortals = (int *)malloc( sizeof( int ) * ( totalLeafPortals > 0 ? totalLeafPortals : 1 ) );
	int lp = 0;
	for ( int l = 0; l < portalclusters; l++ )
	{
		hLeafs[l].portals_start = lp;
		hLeafs[l].portals_count = leafs[l].portals.Count();
		for ( int k = 0; k < leafs[l].portals.Count(); k++ )
			hLeafPortals[lp++] = (int)( leafs[l].portals[k] - portals );
	}

	// -- 3. portalflood -------------------------------------------------------------
	// Size rounded up to a multiple of 4: the kernel writes portalvis as 32-bit words.
	const size_t visBytes = (size_t)numPortals * portalbytes;
	const size_t visBytesPadded = ( visBytes + 3 ) & ~(size_t)3;
	unsigned char *hFlood = (unsigned char *)calloc( visBytesPadded > 0 ? visBytesPadded : 4, 1 );
	for ( int i = 0; i < numPortals; i++ )
		if ( portals[i].portalflood )
			memcpy( hFlood + (size_t)i * portalbytes, portals[i].portalflood, portalbytes );

	unsigned char *hPortalvis = (unsigned char *)malloc( visBytesPadded > 0 ? visBytesPadded : 4 );
	const size_t visAlloc = visBytesPadded > 0 ? visBytesPadded : 4;
	unsigned char *hFloodOrig = (unsigned char *)malloc( visAlloc );
	unsigned char *hAccum = (unsigned char *)calloc( visAlloc, 1 );
	memcpy( hFloodOrig, hFlood, visAlloc );
	const size_t floodBits = PopCountBytes( hFloodOrig, visAlloc );

	const bool useCuda = ( s_backend == BACKEND_CUDA );
	bool success = true;
	double prevRate = 0.0, prevSec = 0.0; // rays per second (pairs x points^2) and duration of the previous pass

	for ( int pass = 0; pass < numPasses && success; pass++ )
	{
	const GPUPassConfig &cfg = passes[pass];
	int samples = cfg.samples;
	const int passFlags = cfg.flags, passRings = cfg.ringmask;
	float passEps = g_EdgeEps;
	const ULONGLONG t0 = GetTickCount64();
	{
		float before = 0.0f;
		for ( int k = 0; k < pass; k++ )
			before += passWeight[k];
		s_progBase = g_bVisDebug ? 0.0f : before / totalWeight;
		s_progScale = g_bVisDebug ? 1.0f : passWeight[pass] / totalWeight;
	}
	if ( pass > 0 )
	{
		for ( size_t b = 0; b < visAlloc; b++ )
			hFlood[b] = hFloodOrig[b] & ~hAccum[b];
	}
	const size_t candBits = PopCountBytes( hFlood, visAlloc );
	if ( passFlags & RAY_FLAG_AUTO )
	{
		// Points per portal: the largest count whose estimated duration fits in the budget.
		int n = 0;
		if ( prevRate > 0.0 && candBits > 0 )
		{
			const double budget = max( (double)cfg.budgetMin, (double)cfg.budgetRel * prevSec );
			n = (int)sqrt( budget * prevRate / (double)candBits );
			if ( n > cfg.samples )
				n = cfg.samples;
		}
		if ( n < 6 )
		{
			if ( g_bVisDebug )
				Msg( "[VVIS GPU] Pass %d/%d : dense pass skipped (%llu candidate pairs, time budget too small).\n", pass + 1, numPasses, (unsigned long long)candBits );
			continue;
		}
		samples = n;
	}
	if ( g_bVisDebug )
	{
		if ( passFlags & RAY_FLAG_HALTON )
			Msg( "[VVIS GPU] Pass %d/%d : dense sampling, %d points/portal, %llu candidate pairs...\n", pass + 1, numPasses, samples, (unsigned long long)candBits );
		else
			Msg( "[VVIS GPU] Pass %d/%d : samples=%d, %llu candidate pairs...\n", pass + 1, numPasses, samples, (unsigned long long)candBits );
	}

	// Per-row progress: cumulative fraction of the candidates of source portals < r.
	float *rowProgress = (float *)malloc( sizeof( float ) * ( (size_t)numPortals + 1 ) );
	{
		double acc = 0.0;
		for ( int r = 0; r < numPortals; r++ )
		{
			rowProgress[r] = candBits ? (float)( acc / (double)candBits ) : 1.0f;
			acc += (double)PopCountBytes( hFlood + (size_t)r * portalbytes, portalbytes );
		}
		rowProgress[numPortals] = 1.0f;
	}
	if ( g_bVisDebug )
	{
		char prefix[64];
		sprintf( prefix, "[VVIS GPU] Pass %d/%d: ", pass + 1, numPasses );
		StartPacifier( prefix );
	}

	// -- Buffers -------------------------------------------------------------------
	bool cudaOk = false;
	bool ok = true;
	if ( useCuda )
	{
		cudaOk = RunRaycastCUDA( hPortals, sizeof( GPUPortal ) * ( numPortals > 0 ? numPortals : 1 ), numPortals,
			hLeafs, sizeof( GPULeaf ) * ( portalclusters > 0 ? portalclusters : 1 ),
			hLeafPortals, sizeof( int ) * ( totalLeafPortals > 0 ? totalLeafPortals : 1 ),
			hWindingPts, sizeof( float ) * 3 * ( totalWindingPts > 0 ? totalWindingPts : 1 ),
			hFlood, hPortalvis, visBytesPadded > 0 ? visBytesPadded : 4,
			portalbytes, samples, portalclusters + 1, passFlags, passEps, passRings, rowProgress );
		ok = false; // skips the whole OpenCL section below
	}
	cl_int err = CL_SUCCESS;
	cl_mem dPortals = NULL, dLeafs = NULL, dLeafPortals = NULL, dWinding = NULL, dFlood = NULL, dVis = NULL;

#define CL_TRY( expr, what ) \
	if ( ok ) { err = ( expr ); if ( err != CL_SUCCESS ) { fprintf( stderr, "[VVIS GPU] %s failed (%d).\n", what, err ); ok = false; } }

#define CL_BUFFER( var, flags, size, host, what ) \
	if ( ok ) { var = cl.CreateBuffer( s_context, flags, size, host, &err ); if ( err != CL_SUCCESS ) { fprintf( stderr, "[VVIS GPU] clCreateBuffer(%s) failed (%d).\n", what, err ); ok = false; } }

	CL_BUFFER( dPortals, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, sizeof( GPUPortal ) * ( numPortals > 0 ? numPortals : 1 ), hPortals, "portals" );
	CL_BUFFER( dLeafs, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, sizeof( GPULeaf ) * ( portalclusters > 0 ? portalclusters : 1 ), hLeafs, "leafs" );
	CL_BUFFER( dLeafPortals, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, sizeof( int ) * ( totalLeafPortals > 0 ? totalLeafPortals : 1 ), hLeafPortals, "leaf_portals" );
	CL_BUFFER( dWinding, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, sizeof( float ) * 3 * ( totalWindingPts > 0 ? totalWindingPts : 1 ), hWindingPts, "winding_pts" );
	CL_BUFFER( dFlood, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, visBytesPadded > 0 ? visBytesPadded : 4, hFlood, "portalflood" );
	CL_BUFFER( dVis, CL_MEM_READ_WRITE, visBytesPadded > 0 ? visBytesPadded : 4, NULL, "portalvis" );

	const cl_uint zero = 0;
	CL_TRY( cl.EnqueueFillBuffer( s_queue, dVis, &zero, sizeof( zero ), 0, visBytesPadded > 0 ? visBytesPadded : 4, 0, NULL, NULL ), "clEnqueueFillBuffer" );

	// -- 4. Kernel -----------------------------------------------------------------
	const int maxSteps = portalclusters + 1;
	cl_uint arg = 0;
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dPortals ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &numPortals ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dLeafs ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &portalclusters ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dLeafPortals ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dWinding ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dFlood ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( cl_mem ), &dVis ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &portalbytes ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &samples ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &maxSteps ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &passFlags ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( float ), &passEps ), "clSetKernelArg" );
	CL_TRY( cl.SetKernelArg( s_kernel, arg++, sizeof( int ), &passRings ), "clSetKernelArg" );

	// Chunks of pairs: each launch stays short so as not to trigger the Windows
	// watchdog (TDR) on GPUs that also drive the display.
	const unsigned long long npairs = (unsigned long long)numPortals * (unsigned long long)numPortals;
	const size_t localSize = 128;
	const size_t chunk = (size_t)localSize * 16384;
	for ( unsigned long long start = 0; ok && start < npairs; start += chunk )
	{
		unsigned long long remaining = npairs - start;
		size_t global = (size_t)( remaining < chunk ? remaining : chunk );
		global = ( global + localSize - 1 ) / localSize * localSize;
		size_t offset = (size_t)start;
		CL_TRY( cl.EnqueueNDRangeKernel( s_queue, s_kernel, 1, &offset, &global, &localSize, 0, NULL, NULL ), "clEnqueueNDRangeKernel" );
		CL_TRY( cl.Finish( s_queue ), "clFinish" );
		if ( ok )
			ReportProgress( PairProgress( rowProgress, numPortals, start + (unsigned long long)global ) );
	}

	// -- 5. Result -----------------------------------------------------------------
	CL_TRY( cl.EnqueueReadBuffer( s_queue, dVis, CL_TRUE, 0, visBytesPadded > 0 ? visBytesPadded : 4, hPortalvis, 0, NULL, NULL ), "clEnqueueReadBuffer" );


	if ( dPortals )     cl.ReleaseMemObject( dPortals );
	if ( dLeafs )       cl.ReleaseMemObject( dLeafs );
	if ( dLeafPortals ) cl.ReleaseMemObject( dLeafPortals );
	if ( dWinding )     cl.ReleaseMemObject( dWinding );
	if ( dFlood )       cl.ReleaseMemObject( dFlood );
	if ( dVis )         cl.ReleaseMemObject( dVis );

	success = useCuda ? cudaOk : ok;
	if ( g_bVisDebug )
		EndPacifier( true );
	free( rowProgress );
	if ( success )
	{
		if ( passFlags & RAY_FLAG_MIRROR )
			SymmetrizeVis( hPortalvis, numPortals, portalbytes );
		// As in the CPU flow, portalvis is always a subset of portalflood. The mirror copy and
		// the portals crossed along the way can fall outside that bound (portalflood is not
		// symmetric): those bits could never be visible on the CPU side, so they are dropped.
		for ( size_t b = 0; b < visAlloc; b++ )
			hAccum[b] |= hPortalvis[b] & hFloodOrig[b];
		const size_t visBits = PopCountBytes( hAccum, visAlloc );
		const double sec = ( GetTickCount64() - t0 ) / 1000.0;
		{
			const double pts = ( passFlags & RAY_FLAG_HALTON ) ? (double)samples : 1.0 + 4.0 * (double)__popcnt( (unsigned)passRings );
			prevSec = sec;
			prevRate = (double)candBits * pts * pts / max( sec, 0.02 );
			// A pass that stops at the first successful ray casts fewer rays per pair than the
			// following dense pass (which only keeps mostly invisible pairs): measured ~2x.
			if ( !( passFlags & RAY_FLAG_EXHAUSTIVE ) && !( passFlags & RAY_FLAG_HALTON ) )
				prevRate *= 0.5;
			// Pass too short: the measured time is mostly fixed overhead, so the rate would be underestimated.
			if ( sec < 0.1 )
				prevRate = max( prevRate, 2.0e8 );
		}
		const int pct = floodBits ? (int)( 100.0 * visBits / floodBits ) : 100;
		char bar[21];
		for ( int k = 0; k < 20; k++ )
			bar[k] = ( k < pct / 5 ) ? '#' : '.';
		bar[20] = 0;
		if ( g_bVisDebug )
			Msg( "[VVIS GPU][%s] Pass %d/%d [%s] %3d%% visible / initial candidates (%llu/%llu) - %.2f s\n",
				useCuda ? "CUDA" : "OpenCL", pass + 1, numPasses, bar, pct,
				(unsigned long long)visBits, (unsigned long long)floodBits, sec );
	}
	}
	s_progBase = 0.0f;
	s_progScale = 1.0f;
	if ( !g_bVisDebug )
	{
		if ( success )
			EndPacifier( false );
		Msg( " (%d)\n", (int)( ( GetTickCount64() - tFlow0 ) / 1000 ) );
	}

#undef CL_TRY
#undef CL_BUFFER

	if ( success )
	{
		for ( int i = 0; i < nportals; i++ )
		{
			portal_t *p = sorted_portals[i];
			if ( !p->portalvis )
				p->portalvis = (byte *)malloc( portalbytes );
			memcpy( p->portalvis, hAccum + (size_t)( p - portals ) * portalbytes, portalbytes );
			p->status = stat_done;
		}
		if ( g_bVisDebug )
			Msg( "[VVIS GPU][RAYCAST][%s] PortalFlow complete : %d portals, %d passes.\n",
				useCuda ? "CUDA" : "OpenCL", nportals, numPasses );
	}

	free( hFloodOrig );
	free( hAccum );
	free( hPortals );
	free( hWindingPts );
	free( hLeafs );
	free( hLeafPortals );
	free( hFlood );
	free( hPortalvis );
	return success;
}
