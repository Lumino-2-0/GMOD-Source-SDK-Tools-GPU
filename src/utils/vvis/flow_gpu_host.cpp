// flow_gpu_host.cpp
//
// Host (CPU) side of the GPU visibility computation (CUDA or OpenCL).
//
// Where it fits in VVIS:
//   BasePortalVis (CPU)               -> portalflood, a coarse superset
//   GPU_RunPortalFlowRaycast (GPU)    -> portalvis, replaces PortalFlow
//   ClusterMerge / CalcPAS (CPU)      -> unchanged
//
// Both APIs are loaded dynamically (LoadLibrary), with no SDK and no static
// linking: nvcuda.dll (NVIDIA driver) and OpenCL.dll (NVIDIA, AMD and Intel
// drivers). The OpenCL types and constants used are redeclared here. Without a
// usable GPU, GPU_Init() returns false and VVIS runs the original CPU flow.
//
// Backend selection:
//   - CUDA first, if an NVIDIA GPU with compute capability >= 7.5 is present. The
//     PTX kernel (flow_gpu_kernel_ptx.h, generated by build_ptx.ps1) is compiled
//     by the driver.
//   - otherwise OpenCL.
//   - VVIS_GPU_BACKEND=opencl forces OpenCL (vvis -opencl option).
//
// Device selection: VVIS_GPU_DEVICE=<n> forces the n-th device; otherwise the one
// with the most compute units is used (in practice the dedicated GPU, not the iGPU).

