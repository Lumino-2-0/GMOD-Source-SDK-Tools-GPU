# Regenerates vrad_gpu_kernel_ptx.h from vrad_gpu_kernel.cu (needs nvcc + Visual Studio).
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$cu  = Join-Path $here 'vrad_gpu_kernel.cu'
$ptx = Join-Path $env:TEMP 'vrad_gpu_kernel.ptx'
$out = Join-Path $here 'vrad_gpu_kernel_ptx.h'
# nvcc requires the x64 host compiler (the cl.exe on PATH may be x86).
# nvcc 12.x only accepts Visual Studio 2017 to 2022, so prefer those versions.
$all = @(Get-ChildItem 'C:\Program Files\Microsoft Visual Studio' -Recurse -Filter vcvars64.bat -ErrorAction SilentlyContinue)
$vcvars = $all | Where-Object { $_.FullName -match '\\(2017|2019|2022)\\' } | Select-Object -First 1
if (-not $vcvars) { $vcvars = $all | Select-Object -First 1 }
if (-not $vcvars) { throw 'vcvars64.bat not found' }
cmd /c "`"$($vcvars.FullName)`" >nul && nvcc -ptx -arch=compute_75 -fmad=false -prec-div=true -prec-sqrt=true -o `"$ptx`" `"$cu`""
if ($LASTEXITCODE -ne 0) { throw 'nvcc failed' }
$bytes = [System.IO.File]::ReadAllBytes($ptx)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by vrad_build_ptx.ps1 from vrad_gpu_kernel.cu - DO NOT EDIT.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('static const unsigned char g_VradTracePTX[] = {')
for ($i = 0; $i -lt $bytes.Length; $i += 24) {
	$n = [Math]::Min(24, $bytes.Length - $i)
	$line = ($bytes[$i..($i + $n - 1)] | ForEach-Object { $_.ToString() }) -join ','
	[void]$sb.AppendLine($line + ',')
}
[void]$sb.AppendLine('0 };')
[System.IO.File]::WriteAllText($out, $sb.ToString())
Write-Host "OK: $($bytes.Length) bytes of PTX -> $out"
